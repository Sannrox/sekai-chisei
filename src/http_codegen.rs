//! Generated HTTP/JSON clients for the stable unary projection (#875).
//!
//! The clients are a transport projection of the ADR 0071 maturity table.
//! They do not invent RPCs, authorization, or a second resource model.

use crate::http_projection::HTTP_PROJECTION_CONTRACT;
use crate::rpc_maturity::{RpcClassification, RpcMaturityTable};

const STREAMING: &[&str] = &["ExecutePlanStream", "ExecuteContentPlanStream"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HttpMethod {
    pub service: String,
    pub rpc: String,
}

pub fn http_unary_methods() -> Vec<HttpMethod> {
    RpcMaturityTable::load()
        .expect("embedded rpc maturity table")
        .entries
        .iter()
        .filter(|entry| entry.classification == RpcClassification::Stable)
        .filter(|entry| !STREAMING.contains(&entry.rpc.as_str()))
        .map(|entry| HttpMethod {
            service: match entry.service.as_str() {
                "SekaiService" => "sekai.SekaiService".into(),
                "ChiseiService" => "chisei.ChiseiService".into(),
                other => other.to_string(),
            },
            rpc: entry.rpc.clone(),
        })
        .collect()
}

pub fn generate_typescript_client() -> String {
    let methods = method_literals();
    format!(
        r#"// Generated by sekai-chisei HTTP projection codegen. DO NOT EDIT.
// contract={contract}

export const HTTP_PROJECTION_CONTRACT = {contract_js};
export const HTTP_UNARY_METHODS = [
{methods}] as const;

export async function invokeHttpJson<T>(
  baseUrl: string,
  service: string,
  rpc: string,
  body: unknown,
  authorization: string,
  headers: Record<string, string> = {{}},
): Promise<T> {{
  const allowed = HTTP_UNARY_METHODS.some((method) => method.service === service && method.rpc === rpc);
  if (!allowed) throw new Error(`rpc is not on the HTTP/JSON projection: ${{service}}/${{rpc}}`);
  const response = await fetch(`${{baseUrl.replace(/\/$/, "")}}/${{service}}/${{rpc}}`, {{
    method: "POST",
    headers: {{
      "content-type": "application/json",
      authorization,
      ...headers,
    }},
    body: JSON.stringify(body ?? {{}}),
  }});
  if (!response.ok) {{
    const text = await response.text();
    try {{
      const payload = JSON.parse(text);
      if (payload && typeof payload === "object" && !Array.isArray(payload)) {{
        throw new Error(payload.message ?? `${{response.status}} ${{response.statusText}}`);
      }}
    }} catch (error) {{
      if (!(error instanceof SyntaxError)) {{
        throw error;
      }}
    }}
    throw new Error(`${{response.status}} ${{response.statusText}}`);
  }}
  return (await response.json()) as T;
}}
"#,
        contract = HTTP_PROJECTION_CONTRACT,
        contract_js = js_string(HTTP_PROJECTION_CONTRACT),
        methods = methods,
    )
}

pub fn generate_python_client() -> String {
    let methods = http_unary_methods()
        .into_iter()
        .map(|method| {
            format!(
                "    ({service}, {rpc}),\n",
                service = py_string(&method.service),
                rpc = py_string(&method.rpc),
            )
        })
        .collect::<String>();
    format!(
        "{header}\n\nfrom __future__ import annotations\n\nimport json\nimport urllib.error\nimport urllib.request\nfrom typing import Any\n\nHTTP_PROJECTION_CONTRACT = {contract}\nHTTP_UNARY_METHODS = (\n{methods})\n\n\ndef invoke_http_json(\n    base_url: str,\n    service: str,\n    rpc: str,\n    body: dict[str, Any] | None,\n    authorization: str,\n    headers: dict[str, str] | None = None,\n) -> Any:\n    if (service, rpc) not in HTTP_UNARY_METHODS:\n        raise ValueError(f\"rpc is not on the HTTP/JSON projection: {{service}}/{{rpc}}\")\n    request = urllib.request.Request(\n        f\"{{base_url.rstrip('/')}}/{{service}}/{{rpc}}\",\n        data=json.dumps({{}} if body is None else body).encode(),\n        method=\"POST\",\n        headers={{\n            \"content-type\": \"application/json\",\n            \"authorization\": authorization,\n            **(headers or {{}}),\n        }},\n    )\n    try:\n        with urllib.request.urlopen(request) as response:\n            return json.load(response)\n    except urllib.error.HTTPError as error:\n        raw = error.read().decode()\n        try:\n            payload = json.loads(raw)\n        except json.JSONDecodeError:\n            raise RuntimeError(f\"{{error.status}} {{error.reason}}\") from error\n        if not isinstance(payload, dict):\n            raise RuntimeError(f\"{{error.status}} {{error.reason}}\") from error\n        raise RuntimeError(payload.get(\"message\") or error.reason) from error\n",
        header = "\"\"\"Generated by sekai-chisei HTTP projection codegen. DO NOT EDIT.\"\"\"",
        contract = py_string(HTTP_PROJECTION_CONTRACT),
        methods = methods,
    )
}

pub fn generate_rust_client() -> String {
    let methods = http_unary_methods()
        .into_iter()
        .map(|method| {
            format!(
                "        ({service}, {rpc}),\n",
                service = rust_string(&method.service),
                rpc = rust_string(&method.rpc),
            )
        })
        .collect::<String>();
    format!(
        r#"// Generated by sekai-chisei HTTP projection codegen. DO NOT EDIT.

pub const HTTP_PROJECTION_CONTRACT: &str = {contract};
pub const HTTP_UNARY_METHODS: &[(&str, &str)] = &[
{methods}];

pub fn http_path(service: &str, rpc: &str) -> Option<String> {{
    HTTP_UNARY_METHODS
        .iter()
        .find(|(hosted, method)| *hosted == service && *method == rpc)
        .map(|(hosted, method)| format!("{{hosted}}/{{method}}"))
}}
"#,
        contract = rust_string(HTTP_PROJECTION_CONTRACT),
        methods = methods,
    )
}

fn method_literals() -> String {
    http_unary_methods()
        .into_iter()
        .map(|method| {
            format!(
                "  {{ service: {service}, rpc: {rpc} }},\n",
                service = js_string(&method.service),
                rpc = js_string(&method.rpc),
            )
        })
        .collect()
}

fn js_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn py_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn rust_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;
    use std::process::Command;

    fn fixture(name: &str) -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures/http_projection")
            .join(name)
    }

    /// `HTTP_CODEGEN_UPDATE=1` rewrites the goldens and the SDK copies after a
    /// stable-set change; review the diff before committing.
    #[test]
    fn generated_http_clients_match_goldens() {
        if std::env::var_os("HTTP_CODEGEN_UPDATE").is_some() {
            let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
            for (path, body) in [
                (fixture("client.v1.ts"), generate_typescript_client()),
                (fixture("client.v1.py"), generate_python_client()),
                (fixture("client.v1.rs"), generate_rust_client()),
                (
                    root.join("sdk/typescript/http.ts"),
                    generate_typescript_client(),
                ),
                (
                    root.join("sdk/python/sekai_http.py"),
                    generate_python_client(),
                ),
            ] {
                fs::write(path, body).unwrap();
            }
        }
        assert_eq!(
            generate_typescript_client(),
            fs::read_to_string(fixture("client.v1.ts")).unwrap()
        );
        assert_eq!(
            generate_python_client(),
            fs::read_to_string(fixture("client.v1.py")).unwrap()
        );
        assert_eq!(
            generate_rust_client(),
            fs::read_to_string(fixture("client.v1.rs")).unwrap()
        );
        assert_eq!(
            generate_typescript_client(),
            fs::read_to_string(
                PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("sdk/typescript/http.ts")
            )
            .unwrap()
        );
        assert_eq!(
            generate_python_client(),
            fs::read_to_string(
                PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("sdk/python/sekai_http.py")
            )
            .unwrap()
        );
        assert!(
            http_unary_methods()
                .iter()
                .any(|method| method.rpc == "EvaluateObjectSet")
        );
        assert!(
            !http_unary_methods()
                .iter()
                .any(|method| method.rpc == "ExecutePlanStream")
        );
    }

    #[test]
    fn typescript_client_checks_ok_before_parsing_json() {
        let src = generate_typescript_client();
        let invoke = src
            .split("export async function invokeHttpJson")
            .nth(1)
            .expect("invokeHttpJson");
        let ok = invoke.find("if (!response.ok)").expect("ok check");
        let json = invoke.find("response.json()").expect("json parse");
        assert!(
            ok < json,
            "generated TypeScript must check response.ok before parsing JSON"
        );
        let error_arm = &invoke[..json];
        assert!(
            error_arm.contains("response.status") && error_arm.contains("response.statusText"),
            "non-JSON errors must carry status and status text"
        );
    }

    /// Plain-text 413/404/405 bodies must surface as RuntimeError with status.
    #[test]
    fn python_client_reports_status_when_error_body_is_not_json() {
        let method = http_unary_methods()
            .into_iter()
            .next()
            .expect("unary method");
        let dir = tempfile::TempDir::new().unwrap();
        fs::write(dir.path().join("sekai_http.py"), generate_python_client()).unwrap();
        fs::write(
            dir.path().join("probe.py"),
            r#"
import http.server
import sys
import threading
from sekai_http import invoke_http_json

class Handler(http.server.BaseHTTPRequestHandler):
    def do_POST(self):
        length = int(self.headers.get("content-length", "0"))
        if length:
            self.rfile.read(length)
        self.send_response(413)
        self.send_header("content-type", "text/plain")
        self.end_headers()
        self.wfile.write(b"payload too large")

    def log_message(self, *_args):
        pass

httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
port = httpd.server_address[1]
threading.Thread(target=httpd.serve_forever, daemon=True).start()
try:
    invoke_http_json(
        f"http://127.0.0.1:{port}",
        sys.argv[1],
        sys.argv[2],
        {},
        "Bearer token",
    )
except RuntimeError as error:
    message = str(error)
    if not message.startswith("413 "):
        raise SystemExit(f"status and reason missing from {message!r}")
else:
    raise SystemExit("expected RuntimeError")
httpd.shutdown()
"#,
        )
        .unwrap();
        let checked = Command::new("python3")
            .args(["probe.py", &method.service, &method.rpc])
            .current_dir(dir.path())
            .output();
        let Ok(checked) = checked else {
            return;
        };
        if !checked.status.success()
            && String::from_utf8_lossy(&checked.stderr).contains("No such file")
        {
            return;
        }
        assert!(
            checked.status.success(),
            "python probe failed: stdout={} stderr={}",
            String::from_utf8_lossy(&checked.stdout),
            String::from_utf8_lossy(&checked.stderr),
        );
    }
}
